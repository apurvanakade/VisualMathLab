// Writes _sidebar.yml, the site's sidebar, from front matter: one section
// per topics/<topic>/index.qmd (in that page's `order:`), holding every
// apps/<slug>/index.qmd whose `topic:` is the topic page's `title:` (in the
// app's `order:`). _quarto.yml loads it through `metadata-files:`.
//
// apps/ is flat, so a sidebar glob can't split it by topic; this script is
// what lets a new page appear in the sidebar without a hand-kept list. It
// runs as a pre-render hook, so every render and preview regenerates it,
// and it fails the render when an app's `topic:` names no topic page,
// rather than leaving that app out of the site's navigation.
//
// The file is rewritten only when its content changes: preview treats a
// changed metadata file as a reason to re-render every page.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outputFile = path.join(repoRoot, '_sidebar.yml')

// One single-line front-matter field, with its surrounding quotes removed;
// null when absent.
export function frontMatterField (source, field) {
  const parts = source.split(/^---$/m)
  if (parts.length < 3) {
    return null
  }
  const match = parts[1].match(new RegExp(`^${field}: (.*)$`, 'm'))
  if (match === null) {
    return null
  }
  let value = match[1].trim()
  if (/^(["']).*\1$/.test(value)) {
    value = value.slice(1, -1)
  }
  return value
}

// [{path, title, topic, order}] for every index.qmd one level under dir.
// Quarto skips folders starting with an underscore (apps/_template), so
// they are skipped here too.
function pages (dir) {
  const result = []
  for (const slug of fs.readdirSync(path.join(repoRoot, dir)).sort()) {
    const file = path.join(repoRoot, dir, slug, 'index.qmd')
    if (slug.startsWith('_') || !fs.existsSync(file)) {
      continue
    }
    const source = fs.readFileSync(file, 'utf8')
    result.push({
      path: `${dir}/${slug}/index.qmd`,
      title: frontMatterField(source, 'title'),
      topic: frontMatterField(source, 'topic'),
      order: Number(frontMatterField(source, 'order'))
    })
  }
  return result
}

function byOrder (a, b) {
  return a.order - b.order
}

// The _sidebar.yml text. Throws on a page that can't be placed.
export function buildSidebar () {
  const problems = []
  const topics = pages('topics')
  const apps = pages('apps')
  for (const page of topics.concat(apps)) {
    if (!Number.isFinite(page.order)) {
      problems.push(`${page.path} has no numeric \`order:\``)
    }
  }

  const appsByTopic = new Map()
  for (const topic of topics) {
    appsByTopic.set(topic.title, [])
  }
  for (const app of apps) {
    if (!appsByTopic.has(app.topic)) {
      problems.push(`${app.path} has topic: "${app.topic}", which is no topics/*/index.qmd title`)
      continue
    }
    appsByTopic.get(app.topic).push(app)
  }
  if (problems.length > 0) {
    throw new Error('build-sidebar: ' + problems.join('\n  '))
  }

  const lines = [
    '# Generated by scripts/build-sidebar.mjs from each page\'s topic:/order:',
    '# front matter -- do not edit. A pre-render hook rewrites it on every render.',
    'website:',
    '  sidebar:',
    '    - style: floating',
    '      contents:'
  ]
  topics.sort(byOrder)
  for (const topic of topics) {
    lines.push(`        - section: ${topic.path}`)
    const members = appsByTopic.get(topic.title)
    members.sort(byOrder)
    if (members.length === 0) {
      lines.push('          contents: []')
      continue
    }
    lines.push('          contents:')
    for (const app of members) {
      lines.push(`            - ${app.path}`)
    }
  }
  return lines.join('\n') + '\n'
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let text
  try {
    text = buildSidebar()
  } catch (error) {
    console.error(error.message)
    process.exit(1)
  }
  let current = null
  if (fs.existsSync(outputFile)) {
    current = fs.readFileSync(outputFile, 'utf8')
  }
  if (current !== text) {
    fs.writeFileSync(outputFile, text)
  }
}
